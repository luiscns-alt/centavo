/** Persisted domain entities (transactions, card purchases, transfers) — the shapes stored in IndexedDB (see core/db.ts). */

/** How money left or entered — lets reports split Pix from card, débito, boleto… */
export type PaymentMethod = 'pix' | 'credit' | 'debit' | 'boleto' | 'cash' | 'ted'

export type TransactionType = 'income' | 'expense' | 'refund'

export interface Transaction {
  id?: number
  /**
   * refund (v7+): money back for an expense (estorno/reembolso). Positive amount that raises the
   * account balance and LOWERS its category's spending — never income. See signedAmount/expenseDelta.
   */
  type: TransactionType
  amount: number        // integer in centavos — R$12,50 → 1250
  categoryId: number    // FK to categories
  accountId: number     // FK to accounts (v4+)
  description?: string
  /** YYYY-MM-DD the money moved — drives account balances and patrimônio */
  date: string
  /**
   * YYYY-MM the amount counts in for reports (Saldo Livre, categorias, Comparativo) (v5+).
   * Equals date's month, except card purchases, which count in their invoice's due month.
   */
  month: string
  method?: PaymentMethod
  // ── Card installments (v5+): only on rows generated from a Purchase
  purchaseId?: number
  installment?: number  // k (1-based)
  installments?: number // N
  invoiceMonth?: string // YYYY-MM of the invoice's due date
  /** Generated by a loan installment / prepayment (v6+) — edited through the loan */
  loanEventId?: number
  /** refund of this transaction (v7+) */
  refundOf?: number
  /** refund of this card purchase (v7+) */
  refundOfPurchase?: number
  createdAt: number     // Unix timestamp ms
  updatedAt?: number
}

/**
 * A credit-card purchase, in 1..N installments. The source of truth for "what was bought";
 * its N expense rows in `transactions` are generated from it in the same DB transaction and
 * regenerated on edit, so they always sum exactly to `total`.
 */
export interface Purchase {
  id?: number
  accountId: number     // the card
  categoryId: number
  description?: string
  total: number         // integer centavos
  installments: number  // N ≥ 1
  date: string          // YYYY-MM-DD purchase date
  firstInvoice: string  // YYYY-MM
  createdAt: number
  updatedAt?: number
}

/**
 * Money moving between two of the user's accounts. One row = one atomic fact: it can't be
 * half-applied, and it is never income or expense, so reports don't need to filter it out.
 */
export interface Transfer {
  id?: number
  fromAccountId: number
  toAccountId: number   // always ≠ fromAccountId
  amount: number        // integer centavos, > 0
  date: string          // YYYY-MM-DD
  description?: string
  /** Set when this transfer pays a credit-card invoice (YYYY-MM of its due date) */
  invoiceMonth?: string
  /** Set on the release of a loan (money from the loan account into the bank) — managed by the loan */
  loanId?: number
  createdAt: number
  updatedAt?: number
}
